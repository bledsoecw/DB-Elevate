import 'server-only';
import { createHash } from 'node:crypto';

/**
 * Optional AI assistance: the provider boundary.
 *
 * Nothing in this directory is reachable unless four separate things are true
 * at once (see `resolveAiRuntime`), and a paid provider additionally requires a
 * server-side sign-off. The default configuration offers no AI at all, and the
 * application has no feature that depends on it — AI being off is not a
 * degraded mode, it is the normal one.
 *
 * What a provider is allowed to return is narrow on purpose: a suggestion is
 * text, with a label saying where it came from, for a person to accept, edit or
 * discard. There is no code path by which a model's output becomes a rating, a
 * score, a compensation figure or an employment decision. Those require an
 * authorized human decision and are written by the services that record who
 * made them.
 */

export type AiProviderName = 'none' | 'mock' | 'anthropic' | 'openai' | 'azure-openai';

export const PAID_PROVIDERS: AiProviderName[] = ['anthropic', 'openai', 'azure-openai'];

export interface SuggestionRequest {
  kind: string;
  /** The assembled, already permission-filtered context. */
  context: string;
  /** What the person asked for, in one line. */
  instruction: string;
  maxWords?: number;
}

export interface SuggestionResult {
  text: string;
  provider: AiProviderName;
  model: string | null;
  /** Proof of what was sent, without storing the content itself. */
  contextDigest: string;
  /** True when no network call was made and nothing was billed. */
  local: boolean;
  /** Shown to the person verbatim, beside the suggestion. */
  sourceLabel: string;
}

export interface AiProvider {
  readonly name: AiProviderName;
  suggest(request: SuggestionRequest): Promise<SuggestionResult>;
}

export function digestContext(context: string): string {
  return createHash('sha256').update(context).digest('hex').slice(0, 32);
}

/**
 * The mock provider.
 *
 * Deterministic: the same request always returns the same text, which is what
 * makes it usable in tests. It makes no network call, needs no credential, and
 * costs nothing. Its output is explicitly labelled as a placeholder in the text
 * itself, so a mock suggestion can never be mistaken for a real one — including
 * if somebody pastes it into a review and forgets where it came from.
 */
export const mockProvider: AiProvider = {
  name: 'mock',
  async suggest(request) {
    const text = mockText(request);
    return {
      text,
      provider: 'mock',
      model: null,
      contextDigest: digestContext(request.context),
      local: true,
      sourceLabel:
        'Placeholder text from the built-in mock provider. No AI service was contacted and nothing was billed.',
    };
  },
};

/** Deterministic fixtures, keyed by suggestion kind. */
function mockText(request: SuggestionRequest): string {
  const prefix = '[MOCK SUGGESTION — not generated by an AI service]';
  const seeded = seededPick(digestContext(request.kind + request.context));

  switch (request.kind) {
    case 'review_question':
      return [
        prefix,
        '',
        'Suggested questions for this section:',
        '',
        '1. Describe a situation this period where you had to adjust the plan on site. What did you change, and what happened?',
        '2. Which part of the work are you most confident in now that you were not six months ago?',
        '3. What is one thing the crew could do differently that would make your job easier?',
        '',
        'Edit these before using them — they are a starting point, not a template.',
      ].join('\n');

    case 'feedback_clarity':
      return [
        prefix,
        '',
        'A clearer version of the same point:',
        '',
        seeded([
          'Consider naming the specific occasion rather than the general pattern — "on the Harrison kitchen you caught the joist spacing before we closed the wall" lands harder than "good attention to detail".',
          'This reads as a judgement about the person rather than a description of the work. Try describing what you observed and what effect it had.',
          'Two separate points are mixed together here. Splitting them would let the reader act on each one.',
        ]),
        '',
        'Your original wording is unchanged until you choose to replace it.',
      ].join('\n');

    case 'review_summary':
      return [
        prefix,
        '',
        'This is where a summary of the submitted reviews would appear. It would be drawn only from',
        'content you can already read, and you would edit it before it became part of any record.',
        '',
        'No rating, score or recommendation is produced here — those are not a model’s to make.',
      ].join('\n');

    case 'goal_wording':
      return [
        prefix,
        '',
        'A more measurable version:',
        '',
        seeded([
          'Add the number and the date: what counts as done, and by when?',
          'This describes an activity rather than an outcome. What would be different if it succeeded?',
          'Consider who else has to act for this to happen, and name them as collaborators.',
        ]),
      ].join('\n');

    case 'meeting_summary':
      return [
        prefix,
        '',
        'A summary of the shared agenda and shared notes would appear here.',
        '',
        'Private notes are excluded from this at the context-assembly layer, regardless of who asks.',
      ].join('\n');

    default:
      return [
        prefix,
        '',
        `No fixture is defined for the suggestion kind "${request.kind}".`,
        'The mock provider returns this rather than inventing something, so a missing fixture is visible.',
      ].join('\n');
  }
}

/** Picks deterministically from a list, so the same input gives the same text. */
function seededPick(seed: string): <T>(options: T[]) => T {
  let cursor = 0;
  for (const char of seed) cursor = (cursor + char.charCodeAt(0)) % 997;
  return <T>(options: T[]): T => options[cursor % options.length] as T;
}

/**
 * A provider that is selected but not implemented in this build.
 *
 * Live providers are deliberately absent. Implementing one means adding the
 * HTTP call here and setting AI_BILLING_APPROVED=true on the server; until
 * both, the application refuses rather than silently falling back to the mock,
 * because a person told "AI is on" should not be reading placeholder text.
 */
function unimplemented(name: AiProviderName): AiProvider {
  return {
    name,
    async suggest() {
      throw new Error(
        `The ${name} provider is selected but no client is implemented in this build. ` +
          'See docs/EXTENSION-PLAN.md ("Optional AI") for the single function to add. ' +
          'Nothing was sent anywhere and nothing was billed.',
      );
    },
  };
}

export function providerByName(name: AiProviderName): AiProvider | null {
  switch (name) {
    case 'mock':
      return mockProvider;
    case 'anthropic':
    case 'openai':
    case 'azure-openai':
      return unimplemented(name);
    case 'none':
      return null;
  }
}
